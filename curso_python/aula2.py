# cada vírgula é um argumento diferente, usando o separador espaço, que é não nomeado
print(12, 34, "Usando o separador não nomeado")

# se quiser alterar o separador, basta usar sep
print(56, 78, "Usando o separador nomeado", sep="-")

# se quiser alterar o final de linha, basta usar end
print(90, 85, "Usando o separador nomeado e final de linha", sep="-", end='\n##')
